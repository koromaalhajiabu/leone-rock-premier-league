-- Leone Rock Premier League: Administrative & Executive Board management
-- Run once in Supabase SQL Editor. Creates a separate board table; does not modify existing league records.

CREATE TABLE IF NOT EXISTS public.league_board_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_type text NOT NULL CHECK (board_type IN ('ADMINISTRATIVE','EXECUTIVE')),
    full_name text NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 120),
    position_title text NOT NULL CHECK (length(trim(position_title)) BETWEEN 2 AND 120),
    photo_url text,
    biography text,
    display_order integer NOT NULL DEFAULT 10 CHECK (display_order BETWEEN 0 AND 9999),
    is_active boolean NOT NULL DEFAULT true,
    created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
    updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS league_board_members_public_order_idx
ON public.league_board_members (is_active, board_type, display_order, full_name);

ALTER TABLE public.league_board_members ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read active league board members" ON public.league_board_members;
CREATE POLICY "Public can read active league board members"
ON public.league_board_members FOR SELECT
TO anon, authenticated
USING (is_active = true);

DROP POLICY IF EXISTS "Developer can read all league board members" ON public.league_board_members;
CREATE POLICY "Developer can read all league board members"
ON public.league_board_members FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND upper(coalesce(up.role, '')) = 'DEVELOPER'
  )
);

DROP POLICY IF EXISTS "Developer can insert league board members" ON public.league_board_members;
CREATE POLICY "Developer can insert league board members"
ON public.league_board_members FOR INSERT
TO authenticated
WITH CHECK (
  updated_by = auth.uid()
  AND EXISTS (
    SELECT 1 FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND upper(coalesce(up.role, '')) = 'DEVELOPER'
  )
);

DROP POLICY IF EXISTS "Developer can update league board members" ON public.league_board_members;
CREATE POLICY "Developer can update league board members"
ON public.league_board_members FOR UPDATE
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND upper(coalesce(up.role, '')) = 'DEVELOPER'
  )
)
WITH CHECK (
  updated_by = auth.uid()
  AND EXISTS (
    SELECT 1 FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND upper(coalesce(up.role, '')) = 'DEVELOPER'
  )
);

DROP POLICY IF EXISTS "Developer can delete league board members" ON public.league_board_members;
CREATE POLICY "Developer can delete league board members"
ON public.league_board_members FOR DELETE
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND upper(coalesce(up.role, '')) = 'DEVELOPER'
  )
);

GRANT SELECT ON public.league_board_members TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.league_board_members TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.league_board_members_id_seq TO authenticated;

-- Verification
