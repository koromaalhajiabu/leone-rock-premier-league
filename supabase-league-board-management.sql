-- Safe to rerun. Does not alter staff or board member records.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.league_role_responsibilities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code text NOT NULL UNIQUE,
    role_title text NOT NULL,
    responsibilities text NOT NULL,
    authority_scope text NOT NULL,
    reports_to text NOT NULL,
    display_order integer NOT NULL DEFAULT 100,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.league_role_responsibilities ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read role responsibilities"
    ON public.league_role_responsibilities;
DROP POLICY IF EXISTS "Managers maintain role responsibilities"
    ON public.league_role_responsibilities;

CREATE POLICY "Public can read role responsibilities"
ON public.league_role_responsibilities
FOR SELECT TO anon, authenticated
USING (is_active = true);

CREATE POLICY "Managers maintain role responsibilities"
ON public.league_role_responsibilities
FOR ALL TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.user_profiles up
        WHERE up.id = (SELECT auth.uid())
          AND upper(coalesce(up.system_role, ''))
              IN ('DEVELOPER', 'SUPER_ADMIN')
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.user_profiles up
        WHERE up.id = (SELECT auth.uid())
          AND upper(coalesce(up.system_role, ''))
              IN ('DEVELOPER', 'SUPER_ADMIN')
    )
);

GRANT SELECT ON public.league_role_responsibilities TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.league_role_responsibilities TO authenticated;
