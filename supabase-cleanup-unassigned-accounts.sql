-- Leone Rock Premier League: Developer tool to remove unassigned accounts
-- DRAFT for review. Do not run until approved.
-- Unassigned = system_role 'VIEWER' (the default for new sign-ups waiting for a role),
-- older than the chosen number of days, with no pending or approved role request.
-- Only the Developer can list or delete. Every deletion is written to account_cleanup_log.

begin;

create table if not exists public.account_cleanup_log (
  id bigint generated by default as identity primary key,
  removed_user_id uuid not null,
  removed_email text,
  removed_full_name text,
  removed_at timestamptz not null default now(),
  removed_by uuid,
  reason text not null default 'Unassigned account removed by Developer'
);

alter table public.account_cleanup_log enable row level security;
revoke all on public.account_cleanup_log from public, anon, authenticated;
grant select on public.account_cleanup_log to authenticated;
drop policy if exists account_cleanup_log_developer_read on public.account_cleanup_log;
create policy account_cleanup_log_developer_read on public.account_cleanup_log
  for select to authenticated
  using (lower(coalesce(public.league_current_role(), '')) = 'developer');

-- 1. List candidates (read-only)
create or replace function public.list_unassigned_accounts(p_older_than_days int default 14)
returns table (user_id uuid, email text, full_name text, created_at timestamptz, days_waiting int)
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if lower(coalesce(public.league_current_role(), '')) <> 'developer' then
    raise exception 'Only the Developer can list unassigned accounts.';
  end if;
  return query
    select up.id, up.email::text, up.full_name::text, up.created_at,
           extract(day from now() - up.created_at)::int
    from public.user_profiles up
    where upper(coalesce(up.system_role, '')) = 'VIEWER'
      and up.created_at < now() - make_interval(days => greatest(p_older_than_days, 1))
      and not exists (
        select 1 from public.role_access_requests r
        where r.auth_user_id = up.id and r.status in ('pending','approved')
      )
      and not exists (
        select 1 from public.club_registration_applications c
        where c.auth_user_id = up.id
      )
    order by up.created_at asc;
end;
$$;

-- 2. Delete only the selected candidates, re-checking every rule at deletion time
create or replace function public.remove_unassigned_accounts(p_user_ids uuid[], p_older_than_days int default 14)
returns int
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_caller uuid := auth.uid();
  v_id uuid;
  v_count int := 0;
  v_email text;
  v_name text;
begin
  if lower(coalesce(public.league_current_role(), '')) <> 'developer' then
    raise exception 'Only the Developer can remove accounts.';
  end if;
  if p_user_ids is null or array_length(p_user_ids, 1) is null then
    return 0;
  end if;

  foreach v_id in array p_user_ids loop
    -- Never remove the Developer's own account or any non-viewer account
    if v_id = v_caller then continue; end if;

    select up.email::text, up.full_name::text into v_email, v_name
    from public.user_profiles up
    where up.id = v_id
      and upper(coalesce(up.system_role, '')) = 'VIEWER'
      and up.created_at < now() - make_interval(days => greatest(p_older_than_days, 1))
      and not exists (select 1 from public.role_access_requests r
                      where r.auth_user_id = up.id and r.status in ('pending','approved'))
      and not exists (select 1 from public.club_registration_applications c
                      where c.auth_user_id = up.id);

    if not found then continue; end if;

    insert into public.account_cleanup_log (removed_user_id, removed_email, removed_full_name, removed_by)
    values (v_id, v_email, v_name, v_caller);

    delete from public.user_profiles where id = v_id;
    delete from auth.users where id = v_id;
    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

revoke all on function public.list_unassigned_accounts(int) from public, anon;
revoke all on function public.remove_unassigned_accounts(uuid[], int) from public, anon;
grant execute on function public.list_unassigned_accounts(int) to authenticated;
grant execute on function public.remove_unassigned_accounts(uuid[], int) to authenticated;

commit;
