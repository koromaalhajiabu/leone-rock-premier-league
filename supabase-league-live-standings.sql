-- Leone Rock Premier League: confirmed final results + automatic standings
-- Run this whole script in Supabase SQL Editor for project ticcaervmjdzbprdpxxv.
-- Additive migration: does not delete existing league records.
begin;

create table if not exists public.match_results (
    id bigint generated by default as identity primary key,
    match_id text not null unique,
    home_team text not null,
    away_team text not null,
    home_goals integer not null check (home_goals between 0 and 30),
    away_goals integer not null check (away_goals between 0 and 30),
    status text not null default 'CONFIRMED' check (status in ('CONFIRMED')),
    recorded_by text,
    confirmed_by uuid references auth.users(id) on delete set null,
    confirmed_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (lower(trim(home_team)) <> lower(trim(away_team))),
    check (trim(home_team) <> '' and trim(away_team) <> '')
);

alter table public.match_results enable row level security;

drop policy if exists "Public can read confirmed match results" on public.match_results;
create policy "Public can read confirmed match results"
on public.match_results for select
to anon, authenticated
using (status = 'CONFIRMED');

drop policy if exists "Assigned referees can record match results" on public.match_results;
create policy "Assigned referees can record match results"
on public.match_results for insert
to authenticated
with check (
    confirmed_by = auth.uid()
    and exists (
        select 1
        from public.match_referee_assignments a
        where a.match_id::text = match_results.match_id
          and a.referee_user_id = auth.uid()
          and a.assignment_status = 'ACTIVE'
    )
);

drop policy if exists "Assigned referees can update match results" on public.match_results;
create policy "Assigned referees can update match results"
on public.match_results for update
to authenticated
using (
    exists (
        select 1
        from public.match_referee_assignments a
        where a.match_id::text = match_results.match_id
          and a.referee_user_id = auth.uid()
          and a.assignment_status = 'ACTIVE'
    )
)
with check (
    confirmed_by = auth.uid()
    and exists (
        select 1
        from public.match_referee_assignments a
        where a.match_id::text = match_results.match_id
          and a.referee_user_id = auth.uid()
          and a.assignment_status = 'ACTIVE'
    )
);

-- Keep timestamps accurate when a result is corrected by an assigned referee.
create or replace function public.set_match_result_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
    new.updated_at := now();
    new.confirmed_at := now();
    return new;
end;
$$;

drop trigger if exists trg_match_result_updated_at on public.match_results;
create trigger trg_match_result_updated_at
before update on public.match_results
for each row execute function public.set_match_result_updated_at();

-- The existing front end expects these column names and an existing unique constraint
-- on league_standings.club. This deliberately refuses to overwrite rows with unknown schema.
alter table public.league_standings
    add column if not exists club text,
    add column if not exists mp integer not null default 0,
    add column if not exists w integer not null default 0,
    add column if not exists d integer not null default 0,
    add column if not exists l integer not null default 0,
    add column if not exists gf integer not null default 0,
    add column if not exists ga integer not null default 0,
    add column if not exists pts integer not null default 0;

-- Create uniqueness only if club values are currently unique; this statement will safely
-- raise an error rather than discard/merge existing duplicate standings rows.
create unique index if not exists league_standings_club_unique_idx
on public.league_standings (club);

create or replace function public.recalculate_leone_rock_standings()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.league_standings (club, mp, w, d, l, gf, ga, pts)
    with teams as (
        select trim(home_team) as club, home_goals as gf, away_goals as ga
        from public.match_results where status = 'CONFIRMED'
        union all
        select trim(away_team) as club, away_goals as gf, home_goals as ga
        from public.match_results where status = 'CONFIRMED'
    ),
    totals as (
        select club,
               count(*)::integer as mp,
               count(*) filter (where gf > ga)::integer as w,
               count(*) filter (where gf = ga)::integer as d,
               count(*) filter (where gf < ga)::integer as l,
               coalesce(sum(gf), 0)::integer as gf,
               coalesce(sum(ga), 0)::integer as ga,
               (count(*) filter (where gf > ga) * 3
                 + count(*) filter (where gf = ga))::integer as pts
        from teams
        group by club
    )
    select club, mp, w, d, l, gf, ga, pts from totals
    on conflict (club) do update set
        mp = excluded.mp, w = excluded.w, d = excluded.d, l = excluded.l,
        gf = excluded.gf, ga = excluded.ga, pts = excluded.pts;

    -- Existing clubs without any confirmed results remain in the table with zero totals.
    update public.league_standings s
    set mp = 0, w = 0, d = 0, l = 0, gf = 0, ga = 0, pts = 0
    where not exists (
        select 1 from public.match_results r
        where r.status = 'CONFIRMED'
          and (lower(trim(r.home_team)) = lower(trim(s.club))
            or lower(trim(r.away_team)) = lower(trim(s.club)))
    );
end;
$$;

create or replace function public.on_match_result_recalculate_standings()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    perform public.recalculate_leone_rock_standings();
    return coalesce(new, old);
end;
$$;

drop trigger if exists trg_match_result_recalculate_standings on public.match_results;
create trigger trg_match_result_recalculate_standings
after insert or update or delete on public.match_results
for each row execute function public.on_match_result_recalculate_standings();

-- Allow the trigger functions to run, but do not grant direct execution to anonymous users.
revoke all on function public.recalculate_leone_rock_standings() from public, anon, authenticated;
revoke all on function public.on_match_result_recalculate_standings() from public, anon, authenticated;
revoke all on function public.set_match_result_updated_at() from public, anon, authenticated;

-- Refresh standings once from whatever confirmed results already exist.
select public.recalculate_leone_rock_standings();

commit;
