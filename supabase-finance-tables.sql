-- Finance tables: transactions, club financial accounts and the finance audit log.
-- Recorded from the live database so the repo matches what is running.
-- Access: Developer, Super Admin and Finance Officer can read and write.
-- Only Developer and Super Admin can delete. Suspended or inactive accounts are blocked.
-- Requires: user_profiles (id, status, system_role) and alert_role(text, text, text).

-- Access check used by every finance policy
CREATE OR REPLACE FUNCTION public.has_finance_access()
RETURNS boolean
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO ''
AS $function$
    SELECT EXISTS (
        SELECT 1
        FROM public.user_profiles AS p
        WHERE p.id = (SELECT auth.uid())
          AND UPPER(p.status) = 'ACTIVE'
          AND UPPER(p.system_role) IN (
              'DEVELOPER',
              'SUPER_ADMIN',
              'FINANCE_OFFICER'
          )
    );
$function$;

-- Income and expense transactions
CREATE TABLE IF NOT EXISTS public.finance_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_date date NOT NULL DEFAULT CURRENT_DATE,
    transaction_type text NOT NULL CHECK (transaction_type = ANY (ARRAY['income'::text, 'expense'::text])),
    category text NOT NULL,
    description text NOT NULL,
    amount numeric NOT NULL CHECK (amount > 0::numeric),
    currency text NOT NULL DEFAULT 'SLE'::text,
    club_name text,
    reference_number text UNIQUE,
    payment_method text,
    payment_status text NOT NULL DEFAULT 'completed'::text
        CHECK (payment_status = ANY (ARRAY['pending'::text, 'completed'::text, 'cancelled'::text])),
    recorded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Per-club balances
CREATE TABLE IF NOT EXISTS public.club_financial_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_name text NOT NULL UNIQUE,
    registration_fees numeric NOT NULL DEFAULT 0 CHECK (registration_fees >= 0::numeric),
    fines numeric NOT NULL DEFAULT 0 CHECK (fines >= 0::numeric),
    other_charges numeric NOT NULL DEFAULT 0 CHECK (other_charges >= 0::numeric),
    payments_received numeric NOT NULL DEFAULT 0 CHECK (payments_received >= 0::numeric),
    notes text,
    updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Audit trail written by trigger for every insert, update and delete
CREATE TABLE IF NOT EXISTS public.finance_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name text NOT NULL,
    record_id text,
    action text NOT NULL,
    changed_by uuid,
    changed_at timestamptz NOT NULL DEFAULT now(),
    old_data jsonb,
    new_data jsonb
);

-- Row-level security
ALTER TABLE public.finance_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.club_financial_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finance_audit_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Finance roles read transactions" ON public.finance_transactions;
CREATE POLICY "Finance roles read transactions" ON public.finance_transactions
    FOR SELECT TO authenticated USING (public.has_finance_access());
DROP POLICY IF EXISTS "Finance roles insert transactions" ON public.finance_transactions;
CREATE POLICY "Finance roles insert transactions" ON public.finance_transactions
    FOR INSERT TO authenticated WITH CHECK (public.has_finance_access());
DROP POLICY IF EXISTS "Finance roles update transactions" ON public.finance_transactions;
CREATE POLICY "Finance roles update transactions" ON public.finance_transactions
    FOR UPDATE TO authenticated USING (public.has_finance_access());
DROP POLICY IF EXISTS "Finance roles delete transactions" ON public.finance_transactions;
CREATE POLICY "Finance roles delete transactions" ON public.finance_transactions
    FOR DELETE TO authenticated USING (EXISTS (
        SELECT 1 FROM public.user_profiles p
        WHERE p.id = (SELECT auth.uid())
          AND UPPER(p.status) = 'ACTIVE'
          AND UPPER(p.system_role) = ANY (ARRAY['DEVELOPER'::text, 'SUPER_ADMIN'::text])));

DROP POLICY IF EXISTS "Finance roles read club accounts" ON public.club_financial_accounts;
CREATE POLICY "Finance roles read club accounts" ON public.club_financial_accounts
    FOR SELECT TO authenticated USING (public.has_finance_access());
DROP POLICY IF EXISTS "Finance roles insert club accounts" ON public.club_financial_accounts;
CREATE POLICY "Finance roles insert club accounts" ON public.club_financial_accounts
    FOR INSERT TO authenticated WITH CHECK (public.has_finance_access());
DROP POLICY IF EXISTS "Finance roles update club accounts" ON public.club_financial_accounts;
CREATE POLICY "Finance roles update club accounts" ON public.club_financial_accounts
    FOR UPDATE TO authenticated USING (public.has_finance_access());
DROP POLICY IF EXISTS "Finance admins delete club accounts" ON public.club_financial_accounts;
CREATE POLICY "Finance admins delete club accounts" ON public.club_financial_accounts
    FOR DELETE TO authenticated USING (EXISTS (
        SELECT 1 FROM public.user_profiles p
        WHERE p.id = (SELECT auth.uid())
          AND UPPER(p.status) = 'ACTIVE'
          AND UPPER(p.system_role) = ANY (ARRAY['DEVELOPER'::text, 'SUPER_ADMIN'::text])));

DROP POLICY IF EXISTS "Finance roles read audit log" ON public.finance_audit_log;
CREATE POLICY "Finance roles read audit log" ON public.finance_audit_log
    FOR SELECT TO authenticated USING (public.has_finance_access());

-- Audit trigger
CREATE OR REPLACE FUNCTION public.record_finance_audit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
    INSERT INTO public.finance_audit_log (
        table_name,
        record_id,
        action,
        changed_by,
        old_data,
        new_data
    )
    VALUES (
        TG_TABLE_NAME,
        CASE
            WHEN TG_OP = 'DELETE' THEN OLD.id::TEXT
            ELSE NEW.id::TEXT
        END,
        TG_OP,
        auth.uid(),
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE')
             THEN to_jsonb(OLD) ELSE NULL END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE')
             THEN to_jsonb(NEW) ELSE NULL END
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS finance_transactions_audit ON public.finance_transactions;
CREATE TRIGGER finance_transactions_audit AFTER INSERT OR DELETE OR UPDATE ON public.finance_transactions
    FOR EACH ROW EXECUTE FUNCTION public.record_finance_audit();
DROP TRIGGER IF EXISTS club_financial_accounts_audit ON public.club_financial_accounts;
CREATE TRIGGER club_financial_accounts_audit AFTER INSERT OR DELETE OR UPDATE ON public.club_financial_accounts
    FOR EACH ROW EXECUTE FUNCTION public.record_finance_audit();

-- Alert the Finance Officer role when a transaction is recorded
CREATE OR REPLACE FUNCTION public.trg_alert_finance_recorded()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
begin
  perform public.alert_role('FINANCE_OFFICER', 'A finance transaction was recorded',
    'A finance transaction has been recorded and may need your review. Sign in to the SLFA system to review it.');
  return new;
end $function$;

DROP TRIGGER IF EXISTS trg_alert_finance_recorded ON public.finance_transactions;
CREATE TRIGGER trg_alert_finance_recorded AFTER INSERT ON public.finance_transactions
    FOR EACH ROW EXECUTE FUNCTION public.trg_alert_finance_recorded();
