-- Season history and automatic suspension flags for the SLFA league.
-- Additive only: nothing existing is removed or changed.
-- Run once in the Supabase SQL editor.

-- 1. Link each match to a season, so records can be shown per season.
alter table public.matches add column if not exists season_id bigint references public.seasons(id);
create index if not exists matches_season_id_idx on public.matches(season_id);

-- 2. Suspension rules per season (card limits and ban lengths).
create table if not exists public.suspension_rules (
  id bigint generated by default as identity primary key,
  season_id bigint references public.seasons(id),
  competition_name text not null default 'League',
  yellow_card_limit integer not null default 3 check (yellow_card_limit > 0),
  red_card_ban_matches integer not null default 1 check (red_card_ban_matches >= 0),
  created_at timestamptz not null default now(),
  unique (season_id, competition_name)
);
alter table public.suspension_rules enable row level security;
drop policy if exists "suspension rules are readable" on public.suspension_rules;
create policy "suspension rules are readable" on public.suspension_rules for select using (true);

-- 3. Automatic flags: each player's cards per season, and whether a suspension is due.
create or replace view public.player_suspension_flags with (security_invoker = true) as
with cards as (
  select e.team_name, e.player_name, m.season_id, e.event_type
  from public.match_events e
  join public.matches m on m.id::text = e.match_id
  where e.event_type in ('YELLOW_CARD', 'RED_CARD') and e.player_name is not null
),
totals as (
  select team_name, player_name, season_id,
         count(*) filter (where event_type = 'YELLOW_CARD') as yellow_cards,
         count(*) filter (where event_type = 'RED_CARD') as red_cards
  from cards
  group by team_name, player_name, season_id
)
select t.team_name, t.player_name, t.season_id, t.yellow_cards, t.red_cards,
       r.yellow_card_limit, r.red_card_ban_matches,
       (t.yellow_cards >= coalesce(r.yellow_card_limit, 3) or t.red_cards > 0) as suspension_due
from totals t
left join public.suspension_rules r
  on r.season_id is not distinct from t.season_id and r.competition_name = 'League';
